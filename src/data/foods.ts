// The food catalogue.
//
// Every number here is sourced, because the whole prototype rests on them:
//
// - Glycaemic index (GI, glucose = 100) is from Atkinson FS, Brand-Miller JC,
//   Foster-Powell K, Buyken AE, Goletzke J. "International tables of glycemic
//   index and glycemic load values 2021: a systematic review." Am J Clin Nutr
//   2021;114(5):1625-32. Where the tables give a range across cultivars or
//   cooking methods (white rice 48-92, potato 56-111), the mid of the
//   ISO-methodology entries is used and the variation is flagged in `note`.
// - Macronutrients per 100 g as eaten are from standard food composition data
//   (USDA FoodData Central / FSANZ AUSNUT reference values).
// - GI is only meaningful for foods with available carbohydrate. Foods with
//   essentially none carry `gi: null`; a spec test enforces that anything with
//   more than 3 g of available carbohydrate per unit declares a GI.
//
// `unitWeightG` is the contract behind the displayed grams: grams shown to the
// visitor are always `units × unitWeightG`, never stored and never rounded into
// state. See `gramsFor` and the CLAUDE.md invariant.

export type Category = "protein" | "carbs" | "veggies" | "fruit" | "sweets" | "fats";

/** Who can eat it. `vegan` items are also shown under the vegetarian filter. */
export type Diet = "vegan" | "vegetarian" | "omnivore";

export type Per100g = {
  carbsG: number;
  fibreG: number;
  proteinG: number;
  fatG: number;
  kcal: number;
};

export type Food = {
  id: string;
  name: string;
  emoji: string;
  category: Category;
  diet: Diet;
  /** What one unit is, in the visitor's language: "1 slice", "1 cup cooked". */
  unit: string;
  /** Grams in one unit. The only source of truth for displayed grams. */
  unitWeightG: number;
  /** Glycaemic index, glucose = 100. `null` when the food has no measurable GI. */
  gi: number | null;
  per100g: Per100g;
  /** Shown in the food's tooltip when there is something worth knowing. */
  note?: string;
};

